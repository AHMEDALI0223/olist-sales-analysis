-- Run in the olist_db database after importing the CSVs.
-- Metric definitions are aligned with the corresponding analyses in P1_Py.ipynb.

-- 1) Monthly sales revenue (BRL): SUM(price), excluding freight.
-- Exclude canceled/unavailable orders; use the notebook's Jan 2017-Aug 2018 window.
-- Item rows are already the revenue grain; COUNT(DISTINCT order_id) is for the order count.
WITH valid_orders AS (
    SELECT
        order_id,
        order_purchase_timestamp
    FROM olist.orders
    WHERE order_status NOT IN ('canceled', 'unavailable')
),
monthly_sales AS (
    SELECT
        DATE_TRUNC('month', o.order_purchase_timestamp)::date AS order_month,
        SUM(oi.price) AS revenue,
        COUNT(DISTINCT o.order_id) AS orders,
        COUNT(*) AS items
    FROM valid_orders AS o
    JOIN olist.order_items AS oi
        ON oi.order_id = o.order_id
    WHERE o.order_purchase_timestamp >= TIMESTAMP '2017-01-01'
      AND o.order_purchase_timestamp <  TIMESTAMP '2018-09-01'
    GROUP BY 1
)
SELECT
    order_month,
    ROUND(revenue, 2) AS revenue,
    orders,
    items
FROM monthly_sales
ORDER BY order_month;


-- 2) Top 10 product categories by sales revenue, matching the Python ranking.
-- Use English labels when available; otherwise use the Portuguese label, or 'unknown'.
WITH valid_orders AS (
    SELECT order_id
    FROM olist.orders
    WHERE order_status NOT IN ('canceled', 'unavailable')
),
category_sales AS (
    SELECT
        COALESCE(t.product_category_name_english, p.product_category_name, 'unknown') AS category,
        SUM(oi.price) AS revenue,
        COUNT(DISTINCT oi.order_id) AS orders,
        AVG(oi.price) AS average_item_price
    FROM valid_orders AS o
    JOIN olist.order_items AS oi
        ON oi.order_id = o.order_id
    JOIN olist.products AS p
        ON p.product_id = oi.product_id
    LEFT JOIN olist.product_category_name_translation AS t
        ON t.product_category_name = p.product_category_name
    GROUP BY 1
)
SELECT
    category,
    ROUND(revenue, 2) AS revenue,
    orders,
    ROUND(average_item_price, 2) AS average_item_price
FROM category_sales
ORDER BY revenue DESC
LIMIT 10;


-- 3) Monthly late-delivery rate by order purchase month.
-- The denominator is delivered orders with both actual and estimated delivery dates.
-- P1_Py.ipynb currently reports an overall rate (8.11%), not this monthly breakdown.
WITH delivered_orders AS (
    SELECT
        order_id,
        DATE_TRUNC('month', order_purchase_timestamp)::date AS order_month,
        order_delivered_customer_date > order_estimated_delivery_date AS is_late
    FROM olist.orders
    WHERE order_status = 'delivered'
      AND order_delivered_customer_date IS NOT NULL
      AND order_estimated_delivery_date IS NOT NULL
)
SELECT
    order_month,
    COUNT(*) FILTER (WHERE is_late) AS late_orders,
    COUNT(*) AS delivered_orders,
    ROUND(100.0 * COUNT(*) FILTER (WHERE is_late) / NULLIF(COUNT(*), 0), 2) AS late_rate_pct
FROM delivered_orders
GROUP BY order_month
ORDER BY order_month;


-- 4) Seller concentration: share of revenue generated by the top 10% of selling sellers.
-- Match Python: valid orders exclude canceled/unavailable; sellers with no valid sales are omitted.
WITH valid_orders AS (
    SELECT order_id
    FROM olist.orders
    WHERE order_status NOT IN ('canceled', 'unavailable')
),
seller_revenue AS (
    SELECT
        oi.seller_id,
        SUM(oi.price) AS revenue
    FROM valid_orders AS o
    JOIN olist.order_items AS oi
        ON oi.order_id = o.order_id
    GROUP BY oi.seller_id
),
ranked_sellers AS (
    SELECT
        seller_id,
        revenue,
        ROW_NUMBER() OVER (ORDER BY revenue DESC, seller_id) AS seller_rank,
        COUNT(*) OVER () AS seller_count,
        SUM(revenue) OVER () AS total_revenue
    FROM seller_revenue
),
seller_decile AS (
    SELECT
        *,
        FLOOR(seller_count * 0.10)::integer AS top_10_percent_count
    FROM ranked_sellers
)
SELECT
    MAX(seller_count) AS sellers_with_sales,
    MAX(top_10_percent_count) AS sellers_in_top_10_pct,
    ROUND(
        100.0 * SUM(revenue) FILTER (WHERE seller_rank <= top_10_percent_count)
        / NULLIF(MAX(total_revenue), 0),
        2
    ) AS top_10_pct_revenue_share
FROM seller_decile;


-- 5) Average review score for late vs on-time delivered orders.
-- Match Python by keeping only the latest review per order (by answer timestamp).
WITH latest_review AS (
    SELECT order_id, review_score
    FROM (
        SELECT
            order_id,
            review_score,
            ROW_NUMBER() OVER (
                PARTITION BY order_id
                ORDER BY review_answer_timestamp DESC
            ) AS review_rank
        FROM olist.order_reviews
    ) AS ranked_reviews
    WHERE review_rank = 1
),
reviewed_delivered_orders AS (
    SELECT
        CASE
            WHEN o.order_delivered_customer_date > o.order_estimated_delivery_date THEN 'Late'
            ELSE 'On time'
        END AS delivery_group,
        r.review_score
    FROM olist.orders AS o
    JOIN latest_review AS r
        ON r.order_id = o.order_id
    WHERE o.order_status = 'delivered'
      AND o.order_delivered_customer_date IS NOT NULL
      AND o.order_estimated_delivery_date IS NOT NULL
)
SELECT
    delivery_group,
    ROUND(AVG(review_score), 2) AS average_review_score,
    COUNT(*) AS orders_with_reviews
FROM reviewed_delivered_orders
GROUP BY delivery_group
ORDER BY delivery_group;
